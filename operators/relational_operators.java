// relational operators are the value checking operators(equal , not equal , less than , greater than)
//(lesser than or equal to , greater than or equal to , and gives output as(boolean) true or false)


public class relational_operators {
    public static void main(String[] args) {
        int a = 10;
        int b = 1;

        System.out.print((a>=b) +"\n");   // greater than or equal to
        System.out.print((a<=b) +"\n");   // lesser than or equal to
        System.out.print((a==b) +"\n");   // equal to
        System.out.print((a!=b) +"\n");   // not equal to
        System.out.print((a>b) +"\n");    // greater than 
        System.out.print((a<b) +"\n");    // lesser than
    }
}
