

public class increment {
    public static void main(String args[])
    {
      int a = 5;
      System.out.print(a++ +"\n");      // output will be 5 because assigning in right side off the                                 // variables gives the same value
                                        // variables gives the same value
      int b = 5;
      System.out.print(++b + "\n");     // now the value will be 6
      
      int c = 10;
      c++;
      System.out.print(c);              // this will add by a value of 1 soo (10+1) output==> 11
    }
}
